async def _llm_filter_atoms(atoms: list) -> list:
    if not atoms:
        return atoms

    from app.config import get_settings
    from app.services.aria_agent import get_groq_client

    settings = get_settings()
    if settings.groq_is_mocked:
        return atoms

    try:
        numbered = "\n".join(
            f"[{i+1}] {a.raw_text}" for i, a in enumerate(atoms)
        )
        client = get_groq_client()
        response = client.chat.completions.create(
            model=settings.GROQ_MODEL,
            messages=[
                {
                    "role": "system",
                    "content": (
                        "You are a requirements analyst. Given a list of requirement statements, "
                        "return ONLY the numbers (comma-separated) of the ones that are unique, "
                        "meaningful, and should be kept in a formal SRS document. "
                        "Exclude: duplicates, near-duplicates, trivial conversational filler, "
                        "greetings, vague non-requirements. "
                        "Reply with ONLY numbers, e.g.: 1,3,5,7"
                    ),
                },
                {
                    "role": "user",
                    "content": f"Filter these requirements:\n{numbered}",
                },
            ],
            timeout=settings.GROQ_TIMEOUT_SECONDS,
        )
        raw = response.choices[0].message.content.strip()
        keep_indices = set()
        for part in raw.split(","):
            part = part.strip()
            if part.isdigit():
                idx = int(part) - 1
                if 0 <= idx < len(atoms):
                    keep_indices.add(idx)
        if not keep_indices:
            return atoms
        return [atoms[i] for i in sorted(keep_indices)]
    except Exception as e:
        logger.warning(f"[SRS LLM filter] Groq filtering failed, returning all atoms: {e}")
        return atoms

@router.get("/project/{project_id}/latest")
async def get_latest_srs(
    project_id: uuid.UUID,
    current_user: User = Depends(require_roles("admin", "developer", "client")),
    db: AsyncSession = Depends(get_db)
):
    await get_scoped_project(project_id, current_user, db)

    q = (
        select(SRSVersion)
        .where(SRSVersion.project_id == project_id)
        .order_by(SRSVersion.created_at.desc())
        .limit(1)
    )
    result = await db.execute(q)
    srs = result.scalar_one_or_none()

    if not srs:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="No SRS document found for this project."
        )

    from app.models.contradiction import Contradiction
    from app.models.session import Session
    from app.models.change_request import ChangeRequest
    from sqlalchemy import or_

    session_ids_q = select(Session.id).where(Session.project_id == project_id)
    cr_ids_q = select(ChangeRequest.id).where(ChangeRequest.project_id == project_id)
    pending_c_res = await db.execute(
        select(Contradiction).where(
            or_(
                Contradiction.session_id.in_(session_ids_q),
                Contradiction.change_request_id.in_(cr_ids_q)
            ),
            Contradiction.status == "pending"
        )
    )
    pending_c_list = pending_c_res.scalars().all()
    pending_atom_ids = set()
    for pc in pending_c_list:
        if pc.atom_1_id:
            pending_atom_ids.add(pc.atom_1_id)
        if pc.atom_2_id:
            pending_atom_ids.add(pc.atom_2_id)

    atoms_res = await db.execute(
        select(RequirementAtom)
        .where(
            (RequirementAtom.session_id == srs.session_id) | (RequirementAtom.project_id == project_id)
        )
        .where(RequirementAtom.status == "active")
    )
    all_active_atoms = atoms_res.scalars().all()
    atoms = [a for a in all_active_atoms if a.id not in pending_atom_ids]

    atoms = await _llm_filter_atoms(atoms)

    sections = [
        {
            "title": "1. Executive Summary & Overview",
            "content": f"Software Requirements Specification (v{srs.version}) generated by {srs.generated_by}. This specification maps all verified functional requirements, constraints, and system specifications captured during client gathering sessions."
        },
        {
            "title": "2. Functional Requirements",
            "content": "\n\n".join([
                f"[{idx}] {atom.subject or 'Unspecified'}: {atom.action or 'Unspecified'}" + (f" (Constraint: {atom.constraint_text})" if atom.constraint_text else "")
                for idx, atom in enumerate(atoms, start=1)
            ]) if atoms else "No active functional requirements extracted yet."
        },
        {
            "title": "3. Requirement Statements (Raw Captures)",
            "content": "\n".join([
                f"- \"{atom.raw_text}\"" for atom in atoms
            ]) if atoms else "No raw requirement statements captured."
        }
    ]

    download_url = StorageService.get_download_url(srs.file_url)

    return {
        "id": srs.id,
        "version": srs.version,
        "download_url": download_url,
        "sections": sections,
        "atoms": [
            {
                "id": str(a.id),
                "subject": a.subject,
                "action": a.action,
                "constraint_text": a.constraint_text,
                "raw_text": a.raw_text
            }
            for a in atoms
        ],
        "created_at": srs.created_at,
        "generated_by": srs.generated_by,
        "change_summary": srs.change_summary
    }

import os
from pathlib import Path
